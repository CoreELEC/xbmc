const AEPassthroughSilentFrame* CAEPassthroughSilence::Find(CAEStreamInfo::DataType type,
                                                            const uint8_t* data,
                                                            unsigned int size)
{
  if (type != CAEStreamInfo::STREAM_TYPE_EAC3)
    return nullptr;

  // ffmpeg ff_ac3_parse_header and eac3_parse_header, read for the one format with a silent frame
  CBitstreamReader bs(data, static_cast<int>(size));
  if (bs.ReadBits(16) != AC3_SYNC_WORD)
    return nullptr;

  const uint32_t strmtyp = bs.ReadBits(2);
  const uint32_t substreamid = bs.ReadBits(3);
  const uint32_t frameSize = (bs.ReadBits(11) + 1) * 2;
  const uint32_t fscod = bs.ReadBits(2);
  const uint32_t numblkscod = bs.ReadBits(2);
  const uint32_t acmod = bs.ReadBits(3);
  const uint32_t lfeon = bs.ReadBits(1);
  const uint32_t bsid = bs.ReadBits(5);
  // a dependent frame joined on makes the buffer longer than the frame
  if (bsid < EAC3_MIN_BSID || bsid > EAC3_MAX_BSID || strmtyp != STRMTYP_INDEPENDENT ||
      substreamid != 0 || frameSize != size || fscod != FSCOD_48KHZ ||
      numblkscod != NUMBLKSCOD_6_BLOCKS || acmod != ACMOD_3F2R || lfeon != 1)
    return nullptr;

  // dialnorm, compre and compr
  bs.SkipBits(5);
  if (bs.ReadBits(1))
    bs.SkipBits(8);

  // mixmdate: dmixmod and the center and surround mix levels, then lfemixlevcode
  if (bs.ReadBits(1))
  {
    bs.SkipBits(14);
    if (bs.ReadBits(1))
      bs.SkipBits(5);
    // pgmscle, extpgmscle
    if (bs.ReadBits(1))
      bs.SkipBits(6);
    if (bs.ReadBits(1))
      bs.SkipBits(6);
    switch (bs.ReadBits(2))
    {
      case 1:
        bs.SkipBits(5);
        break;
      case 2:
        bs.SkipBits(12);
        break;
      case 3:
        bs.SkipBits((bs.ReadBits(5) + 2) * 8);
        break;
      default:
        break;
    }
    // frmmixcfginfoe, then blkmixcfginfoe per block
    if (bs.ReadBits(1))
    {
      for (int block = 0; block < EAC3_BLOCKS; block++)
      {
        if (bs.ReadBits(1))
          bs.SkipBits(5);
      }
    }
  }

  // infomdate: bsmod, copyrightb, origbs, dsurexmod, then the mix level, room type and A/D
  // converter type, and sourcefscod
  if (bs.ReadBits(1))
  {
    bs.SkipBits(7);
    if (bs.ReadBits(1))
      bs.SkipBits(8);
    bs.SkipBits(1);
  }

  // addbsie and addbsil; the last bit of the first addbsi byte flags Atmos
  // (flag_ec3_extension_type_a)
  if (!bs.ReadBits(1))
    return nullptr;
  bs.SkipBits(6 + 7);
  if (!bs.ReadBits(1) || bs.Overflow())
    return nullptr;

  return &EAC3_ATMOS_51_48KHZ_SILENCE;
}
